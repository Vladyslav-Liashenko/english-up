window.IDIOMS = {};
(function () {
  var cur = null;
  window.IDIOMS_RAW.trim().split('\n').forEach(function (l) {
    if (l.charAt(0) === '#') { cur = l.slice(2).trim(); window.IDIOMS[cur] = []; return; }
    var p = l.split('|');
    if (cur && p.length >= 4) window.IDIOMS[cur].push({ w: p[0], uk: p[1], ru: p[2], ex: p[3], kind: 'i' });
  });
})();

// 2 ідіоми на урок: урок n рівня бере ідіоми (n-1)*2 та (n-1)*2+1
window.lessonIdioms = function (level, n) {
  var list = window.IDIOMS[level] || [];
  if (!list.length) return [];
  var i = ((n - 1) * 2) % list.length;
  return [list[i], list[(i + 1) % list.length]];
};
